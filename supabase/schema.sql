-- Existing portfolio.json structure.
do $$
declare
  static_group uuid;
  carousel_group uuid;
begin
  if not exists (select 1 from public.portfolio_groups where tab = 'estaticos') then
    insert into public.portfolio_groups (tab, client, meta, position)
    values ('estaticos', 'Nome do Cliente', 'Categoria · Descrição breve', 0)
    returning id into static_group;

    insert into public.portfolio_items (group_id, position, image, caption)
    values
      (static_group, 0, null, ''),
      (static_group, 1, null, ''),
      (static_group, 2, null, '');
  end if;

  if not exists (select 1 from public.portfolio_groups where tab = 'carrosseis') then
    insert into public.portfolio_groups (tab, client, meta, handle, position)
    values ('carrosseis', 'Nome do Cliente', 'Categoria · Descrição breve', '', 0)
    returning id into carousel_group;

    insert into public.portfolio_items (group_id, position, images, caption)
    values (carousel_group, 0, '[]'::jsonb, '');
  end if;
end $$;

