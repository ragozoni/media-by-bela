-- Run this in Supabase SQL Editor.
--
-- Authentication is delegated to Supabase Auth. The Cloudflare Worker
-- receives the existing "username" field, maps it to an admin email, and
-- signs in with Supabase Auth using email + password.
--
-- IMPORTANT:
-- Supabase Auth cannot import the old Werkzeug scrypt hash directly.
-- Create the admin user once in Authentication > Users, then insert its
-- Auth user UUID into public.admins as described in README.md.

create extension if not exists pgcrypto;

create table if not exists public.site_settings (
  id integer primary key,
  links jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  username text not null unique,
  email text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.portfolio_groups (
  id uuid primary key default gen_random_uuid(),
  tab text not null check (tab in ('estaticos', 'carrosseis', 'stories')),
  client text not null default '',
  meta text not null default '',
  handle text,
  position integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists portfolio_groups_tab_position_idx
  on public.portfolio_groups (tab, position);

create table if not exists public.portfolio_items (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.portfolio_groups(id) on delete cascade,
  position integer not null default 0,
  image text,
  caption text not null default '',
  count integer not null default 0,
  link text,
  images jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists portfolio_items_group_position_idx
  on public.portfolio_items (group_id, position);

alter table public.site_settings enable row level security;
alter table public.admins enable row level security;
alter table public.portfolio_groups enable row level security;
alter table public.portfolio_items enable row level security;

